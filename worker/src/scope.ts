/**
 * Mode and scope validation.
 *
 * The scope key is the one attacker-controlled string that reaches a database
 * primary key, which makes it the cheapest denial-of-service in the system: a
 * loop over random playlist ids writes a row per request until the day's write
 * quota is gone. So ids are shape-checked, then collapsed against an allowlist
 * — anything unrecognised becomes the single row `other`.
 *
 * That does lose per-playlist detail for playlists nobody curated. It is worth
 * it: those averages were never meaningful anyway, since a score in the
 * free-play modes is bounded by the playlist it was scored on.
 */

export const MODES = ['daily', 'timeline', 'olderYounger'] as const;
export type Mode = (typeof MODES)[number];

export function isMode(v: unknown): v is Mode {
  return typeof v === 'string' && (MODES as readonly string[]).includes(v);
}

/**
 * Whether a lower score is better.
 *
 * Derived from the mode HERE and nowhere else, and never read off the request.
 * Getting it backwards makes "best" mean "worst" and does not look wrong on a
 * dashboard — the most embarrassing available bug, and a one-liner to prevent.
 */
export function directionFor(mode: Mode): 'min' | 'max' {
  return mode === 'daily' ? 'min' : 'max';
}

/**
 * Playlists whose scores are worth keeping apart.
 *
 * Keep this short and hand-maintained. `DEFAULT_PLAYLIST` in the game's store
 * is the one that matters; everything else is a curiosity.
 */
export const PLAYLIST_ALLOWLIST = new Set<string>(['deezer:15689112801']);

const DAILY_SCOPE = /^d:\d{4}-\d{2}-\d{2}$/;
const PLAYLIST_SCOPE = /^[a-z]{1,16}:\d{1,20}$/;

/**
 * Canonical scope for a request, or null if the shape is wrong.
 *
 * Daily scopes are NOT allowlisted — the date is generated by the game, is
 * bounded by the calendar, and each one is a genuinely distinct puzzle. A
 * nonsense date still has to pass the shape check and gets its own row, which
 * is why the plausibility window in index.ts also applies.
 */
export function canonicalScope(mode: Mode, raw: unknown): string | null {
  if (typeof raw !== 'string' || raw.length > 64) return null;

  if (mode === 'daily') return DAILY_SCOPE.test(raw) ? raw : null;

  if (!PLAYLIST_SCOPE.test(raw)) return null;
  return PLAYLIST_ALLOWLIST.has(raw) ? raw : 'other';
}

/**
 * Plausible score ranges, per mode.
 *
 * Not security — a cheater picks a plausible number. This is about keeping one
 * absurd value out of an average: a single `Number.MAX_SAFE_INTEGER` would
 * otherwise make the mean meaningless for the whole day.
 */
const SCORE_LIMITS: Record<Mode, { min: number; max: number }> = {
  // 5 s is below any human run of ten rounds; 6 h is past any real session.
  daily: { min: 5_000, max: 21_600_000 },
  timeline: { min: 0, max: 500 },
  olderYounger: { min: 0, max: 500 },
};

export function scoreInRange(mode: Mode, score: unknown): score is number {
  if (typeof score !== 'number' || !Number.isFinite(score)) return false;
  const { min, max } = SCORE_LIMITS[mode];
  return Number.isInteger(score) && score >= min && score <= max;
}
